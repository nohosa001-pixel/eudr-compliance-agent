def get_i18n_dict(lang: str = "en") -> Dict[str, str]:
    """Returns localized string dictionary for given language code with fallback to EN."""
    normalized = str(lang or "en").lower().strip()
    if normalized in TRANSLATIONS:
        return TRANSLATIONS[normalized]
    # Check 2-letter prefix if code like 'ko-KR' is passed
    prefix = normalized.split("-")[0].split("_")[0]
    if prefix in TRANSLATIONS:
        return TRANSLATIONS[prefix]
    return TRANSLATIONS["en"]


